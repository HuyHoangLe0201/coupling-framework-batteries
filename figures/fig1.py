"""
fig1.py -- Figure 1: the coupling map.

FIGURE TYPE: 100% schematic. It encodes a TOPOLOGY (which node feeds which, and
whether that relation is measured or inferred), not measurements. No axis, no
scale, no plotted quantity. Every geometric position is specified in
10-si/S5-figure-specs.md S5.1 so that the layout is reproducible rather than
"whatever looked right".

NO AI ARTWORK: drawn entirely with matplotlib primitives (boxes, arrows, text).
Nothing is loaded from an image file and nothing is generated by an image model.

WHAT THIS FIGURE MUST NOT IMPLY
  It carries no numeric loop gain. The reduced model does not compute a physical
  gain for a real cell, and printing one would be read as a prediction. The four
  badges read "G_A".."G_D" and the caption supplies the G = 1 claim.
"""

import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch, Circle

import figstyle as S

W, H = S.W_TWO_COL, 11.6          # cm


def box(ax, x, y, w, h, label, fc="white", ec=S.INK, lw=0.9, fs=7,
        weight="normal", rounding=0.02, z=3):
    p = FancyBboxPatch((x - w / 2, y - h / 2), w, h,
                       boxstyle="round,pad=0,rounding_size={}".format(rounding),
                       facecolor=fc, edgecolor=ec, lw=lw, zorder=z,
                       mutation_aspect=1)
    ax.add_patch(p)
    ax.text(x, y, label, ha="center", va="center", fontsize=fs,
            fontweight=weight, zorder=z + 1, linespacing=1.15)
    return p


def badge(ax, x, y, txt, fc=S.INK, tc="white", r=0.011):
    ax.add_patch(Circle((x, y), r, facecolor=fc, edgecolor="none", zorder=7))
    ax.text(x, y, txt, ha="center", va="center", fontsize=6, color=tc,
            fontweight="bold", zorder=8)


def arrow(ax, p0, p1, measured=True, rad=0.0, color=S.LOOP, lw=1.2, z=5):
    """Solid = measured/evidenced; dashed = inferred. The grammar is fixed in
    S5.0 and reused in Figures 3 and 4."""
    a = FancyArrowPatch(p0, p1, arrowstyle="-|>", mutation_scale=7,
                        lw=lw, color=color, zorder=z,
                        linestyle=S.MEASURED_LS if measured else S.INFERRED_LS,
                        connectionstyle="arc3,rad={}".format(rad),
                        shrinkA=2, shrinkB=2)
    ax.add_patch(a)
    return a


def build():
    S.apply_style()
    fig = S.figure(W, H)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")

    # ---------------------------------------------------------------
    # Cell cross-section scaffold: cathode | separator | anode.
    # Drawn as faint bands so the reader sees a physical cell, because the
    # loops only close through transport across it.
    # ---------------------------------------------------------------
    ax.add_patch(plt.Rectangle((0.02, 0.10), 0.24, 0.80, facecolor="#f7f9fc",
                               edgecolor=S.FAINT, lw=0.6, zorder=0))
    ax.add_patch(plt.Rectangle((0.40, 0.10), 0.10, 0.80, facecolor="#f2f2f2",
                               edgecolor=S.FAINT, lw=0.6, zorder=0,
                               hatch="||||"))
    ax.add_patch(plt.Rectangle((0.62, 0.10), 0.24, 0.80, facecolor="#f7f9fc",
                               edgecolor=S.FAINT, lw=0.6, zorder=0))

    ax.text(0.14, 0.935, "CATHODE", ha="center", fontsize=6.5, color=S.KL)
    ax.text(0.45, 0.935, "SEPARATOR", ha="center", fontsize=6.5, color=S.KL,
            rotation=0)
    ax.text(0.74, 0.935, "ANODE", ha="center", fontsize=6.5, color=S.KL)
    ax.annotate("", xy=(0.03, 0.055), xytext=(0.86, 0.055),
                arrowprops=dict(arrowstyle="->", lw=0.5, color=S.FAINT))
    ax.text(0.445, 0.022, "low potential", ha="center", fontsize=6, color=S.KL)
    ax.text(0.03, 0.022, "high", ha="left", fontsize=6, color=S.KL)

    # ---------------------------------------------------------------
    # The 8 nodes. Positions follow S5.1's x/y fractions, rescaled into the
    # panel region so the cross-section bands line up with the mechanism sides.
    # ---------------------------------------------------------------
    # SOURCE mechanisms (amplifier glyphs), cathode side
    box(ax, 0.135, 0.760, 0.145, 0.085,
        "M3  dissolution\n& reconstruction", fs=6.5)
    badge(ax, 0.198, 0.797, "×N", fc=S.INK)
    box(ax, 0.135, 0.300, 0.145, 0.085, "M4  fracture /\nchemomechanical", fs=6.5)
    badge(ax, 0.198, 0.337, "×N", fc=S.INK)

    # Hubs: state variables, heavy black outline, unfilled (S5.1)
    box(ax, 0.315, 0.545, 0.105, 0.070, "fresh\nsurface", lw=1.8, fs=6.5)
    box(ax, 0.545, 0.300, 0.115, 0.070, "local\noverpotential", lw=1.8, fs=6.5)

    # SINK mechanisms (consumer glyphs), anode side
    box(ax, 0.760, 0.760, 0.130, 0.085, "M1  SEI growth /\nre-formation", fs=6.5)
    badge(ax, 0.816, 0.797, "−1")
    box(ax, 0.760, 0.545, 0.130, 0.085, "M2  Li plating /\ndead Li", fs=6.5)
    badge(ax, 0.816, 0.582, "−1")

    # Loop D's state variable: the electrolyte inventory reservoir, centre.
    ax.add_patch(plt.Rectangle((0.443, 0.400), 0.030, 0.260, facecolor="white",
                               edgecolor=S.INK, lw=1.6, zorder=3))
    ax.add_patch(plt.Rectangle((0.443, 0.400), 0.030, 0.095,
                               facecolor=S.KL, edgecolor="none", zorder=4,
                               alpha=0.45))
    ax.text(0.458, 0.370, "salt &\nsolvent", ha="center", va="top", fontsize=6,
            color=S.INK)
    ax.text(0.458, 0.690, "inventory", ha="center", va="bottom", fontsize=6,
            color=S.INK)

    # ---------------------------------------------------------------
    # The four loops, routed explicitly (S5.1). Loop A and C thick/measured;
    # B medium with one inferred leg; D thin dashed (deliberately weakest).
    # ---------------------------------------------------------------
    # Loop A: M2 -> dead Li -> M1 -> up eta -> M2
    arrow(ax, (0.760, 0.560), (0.760, 0.700), measured=True, rad=-0.35, lw=1.5)
    arrow(ax, (0.700, 0.720), (0.640, 0.400), measured=True, rad=0.30, lw=1.5)
    arrow(ax, (0.600, 0.345), (0.700, 0.500), measured=True, rad=-0.30, lw=1.5)
    ax.text(0.905, 0.700, "A", fontsize=8, fontweight="bold", color=S.LOOP,
            ha="center", va="center")
    ax.text(0.672, 0.600, "closes when Δη/cycle\n> margin to 0 V",
            fontsize=6, color=S.LOOP, ha="center", va="center")

    # Loop B: M3 -> TM ions across separator -> anode interphase -> LLI
    # The crossover is the only loop that physically crosses the cell.
    ax.annotate("", xy=(0.700, 0.815), xytext=(0.215, 0.800),
                arrowprops=dict(arrowstyle="->", lw=1.0, color=S.LOOP,
                                ls=(0, (1, 1.6)), shrinkA=1, shrinkB=1))
    ax.text(0.455, 0.845, "TM ion crossover", fontsize=6, color=S.LOOP,
            ha="center", va="bottom")
    # return leg: partly inferred -> hollow / dashed (S5.1, toc-graphic S3.3)
    arrow(ax, (0.700, 0.740), (0.215, 0.740), measured=False, rad=0.32, lw=1.0)
    ax.text(0.520, 0.640, "acid regenerated — partly inferred", fontsize=6,
            color=S.LOOP, ha="center", va="top", style="italic")
    ax.text(0.455, 0.905, "B", fontsize=8, fontweight="bold", color=S.LOOP,
            ha="center", va="center")

    # Loop C: M4 -> fresh surface -> M1 -> SEI volume/stress -> M4
    arrow(ax, (0.190, 0.345), (0.265, 0.510), measured=True, rad=-0.25, lw=1.5)
    arrow(ax, (0.370, 0.560), (0.700, 0.730), measured=True, rad=-0.22, lw=1.5)
    ax.text(0.360, 0.430, "C", fontsize=8, fontweight="bold", color=S.LOOP,
            ha="center", va="center")
    ax.text(0.300, 0.235, "LAM leads LLI", fontsize=6, color=S.LOOP,
            ha="center", va="top")

    # Loop D: inventory -> eta -> M2 and -> cathode potential -> M3. Weakest.
    arrow(ax, (0.478, 0.470), (0.520, 0.330), measured=False, rad=-0.25, lw=0.7)
    arrow(ax, (0.443, 0.640), (0.330, 0.760), measured=False, rad=-0.30, lw=0.7)
    ax.text(0.545, 0.245, "D  (emerging — least evidence)", fontsize=6,
            color=S.LOOP, ha="left", va="top", style="italic")

    # ---------------------------------------------------------------
    # Right margin: the ledger. Bridges Figure 1 to Figure 2.
    # ---------------------------------------------------------------
    ax.text(0.905, 0.900, "LEDGER", fontsize=6.5, ha="center", color=S.INK,
            fontweight="bold")
    for i, (lbl, col, hh) in enumerate([("LLI", S.LLI, 0.30),
                                       ("LAM", S.LAM, 0.20),
                                       ("KL", S.KL, 0.13)]):
        x = 0.870 + i * 0.042
        ax.add_patch(plt.Rectangle((x, 0.560), 0.032, hh, facecolor=col,
                                   edgecolor="none", zorder=3))
        ax.text(x + 0.016, 0.545, lbl, fontsize=6, ha="center", va="top",
                color=S.INK)
    ax.annotate("", xy=(0.870, 0.500), xytext=(0.990, 0.500),
                arrowprops=dict(arrowstyle="->", lw=0.6, color=S.INK))
    ax.text(0.930, 0.470, "accumulates", fontsize=6, ha="center", va="top",
            color=S.INK)

    # Legend: the arrow grammar, stated once.
    ax.annotate("", xy=(0.640, 0.148), xytext=(0.600, 0.148),
                arrowprops=dict(arrowstyle="-|>", lw=1.2, color=S.LOOP,
                                mutation_scale=7))
    ax.text(0.648, 0.148, "measured / evidenced", fontsize=6, va="center")
    ax.annotate("", xy=(0.640, 0.108), xytext=(0.600, 0.108),
                arrowprops=dict(arrowstyle="-|>", lw=1.0, color=S.LOOP,
                                ls=(0, (4, 2)), mutation_scale=7))
    ax.text(0.648, 0.108, "inferred", fontsize=6, va="center")
    ax.text(0.600, 0.163, "Arrow grammar", fontsize=6.5, va="bottom",
            fontweight="bold")

    # Eight-node / eleven-arrow budget, checked by eye-of-the-code not by a human.
    S.save(fig, "fig1-coupling-map", W, H)
    return fig


if __name__ == "__main__":
    build()
