"""
figstyle.py -- shared style, palette and export for research/11-figures/.

WHY THIS FILE EXISTS
  Four figures plus a TOC image must satisfy the SAME journal constraints:
  exact column widths (8.4 or 17.8 cm), one typeface, one type size, >=300 dpi
  raster, vector PDF. If each script restated those numbers, they would drift.
  They are defined once here and imported.

PROVENANCE OF THE CONSTRAINTS
  02-journal-fit/batteries-and-supercaps-scope.md:
    ">=300 dpi, sans-serif (Arial) labels, one-column max 8.4 cm / two-column
     max 17.8 cm, text 1.5-2 mm (~7-8 pt)"
  09-submission/toc-graphic.md: TOC 5.5x5.0 cm or 11.5x2.5 cm, min 6-7 pt.
  10-si/S5-figure-specs.md S5.0: colour semantics and arrow grammar.

TYPEFACE AND SIZE -- CHANGED 2026-11-05 BY AUTHOR INSTRUCTION
  The artwork previously used Arial at a spread of 6.0-8.6 pt. The author's
  instruction was: "the lettering must use the same typeface as the body text,
  at 8 pt". Both halves of that are now enforced here:

    * FAMILY = Times New Roman, because that is the body-text face of the Wiley
      template this Perspective will be converted into. This DIVERGES from the
      Notice to Authors' graphics guidance, which asks for sans-serif labels; the
      divergence is deliberate and recorded in S5-figure-specs.md S5.0a and in
      AUDIT-CONSTRAINTS.md, so it is a decision rather than an oversight.
    * ONE SIZE = 8.0 pt for every label in the artwork. The old figure ran twelve
      distinct sizes (6.0, 6.1, 6.2, 6.3, 6.4, 6.5, 6.6, 6.8, 7.1, 7.5, 7.6, 8.2,
      8.6), which is a large part of why it read as cluttered: nothing told the
      eye what the hierarchy was. Panel titles are the single exception at 9.5 pt,
      because a title that is the same size as its labels is not a title.

  Times New Roman also removes a constraint that shaped the old design: it HAS
  U+207B (superscript minus), which Arial on this machine lacked, so `cm^-2` no
  longer has to be written with an ASCII caret. Plain strings are still used
  rather than mathtext, because mathtext renders super/subscripts at 0.7x and
  would breach the size floor from an 8 pt parent.

NO AI ARTWORK
  Every figure here is drawn with matplotlib primitives or plotted from
  loopA_model_v4.py output. Nothing is generated by an image model, and nothing
  is traced from a third-party publication. See README.md.
"""

import matplotlib
matplotlib.use("Agg")  # headless: this project is run non-interactively

import os
import matplotlib.pyplot as plt
from matplotlib import rcParams

# Output always goes beside this module, never to the caller's CWD. Writing to
# the CWD silently produced figures in the workspace root during development.
HERE = os.path.dirname(os.path.abspath(__file__))

# ---------------------------------------------------------------------------
# Geometry. Journal column widths, in centimetres. NOTHING ELSE IS PERMITTED.
# ---------------------------------------------------------------------------
CM = 1.0 / 2.54          # cm -> inch
W_ONE_COL = 8.4          # cm
W_TWO_COL = 17.8         # cm
W_TOC_BANNER = 11.5      # cm  (journal option B, recommended by toc-graphic.md)
H_TOC_BANNER = 2.5       # cm
W_TOC_SQUARE = 5.5       # cm  (journal option A, alternate)
H_TOC_SQUARE = 5.0       # cm

DPI = 600                # raster export; journal floor is 300, we double it

# ---------------------------------------------------------------------------
# Type. ONE FAMILY, ONE SIZE for every label. See the module docstring.
# ---------------------------------------------------------------------------
FAMILY = "Times New Roman"
LABEL_PT = 8.0           # every label in every figure, without exception
TITLE_PT = 9.5           # panel titles and panel letters: the only step above
MIN_PT = LABEL_PT
LH_FLOOR = 0.25          # printable hairline floor, pt
LH_STRUCT = 0.50         # structure: boundaries, node outlines
LH_ARROW = 1.20          # the single load-bearing arrow in a panel        # hard floor asserted by figure-spec-check.py

# ---------------------------------------------------------------------------
# Palette. Fixed across ALL figures -- S5.0 calls this "never extended".
# ---------------------------------------------------------------------------
LLI = "#1f5fa8"          # blue   -- lithium-inventory loss
LAM = "#e07b27"          # orange -- loss of active material
KL = "#8c8c8c"           # grey   -- kinetic loss
TL = "#7b4fa8"           # purple -- thermodynamic/potential loss (energy only)
LOOP = "#2e7d32"         # green  -- loop arrows
INK = "#1a1a1a"          # near-black text and node outlines
FAINT = "#c9c9c9"        # light grey for guides
WARN = "#b3261e"         # dark red, used ONLY for "separability fails" markers
PANEL_BG = "#f4f4f4"     # very light grey for schematic watermarks

# Arrow grammar: solid = measured/evidenced, hollow|dashed = inferred.
MEASURED_LS = "-"
INFERRED_LS = (0, (4, 2))


def apply_style():
    """Set rcParams once. Raises if the declared family is unavailable rather
    than silently substituting, because a silent DejaVu fallback would pass a
    font-size check while failing the actual requirement."""
    available = {f.name for f in matplotlib.font_manager.fontManager.ttflist}
    if FAMILY not in available:
        raise RuntimeError(
            "%r not found. The figure must match the body-text typeface, and this "
            "project refuses to silently substitute another face (a fallback would "
            "pass a size check while failing the typeface requirement). Install "
            "the font, or change FAMILY here and record the change in "
            "S5-figure-specs.md." % FAMILY
        )
    rcParams.update({
        "font.family": "serif",
        "font.serif": [FAMILY],
        "font.size": LABEL_PT,
        "axes.labelsize": LABEL_PT,
        "axes.titlesize": TITLE_PT,
        "xtick.labelsize": LABEL_PT,
        "ytick.labelsize": LABEL_PT,
        "legend.fontsize": LABEL_PT,
        "axes.linewidth": 0.6,
        "axes.edgecolor": INK,
        "axes.labelcolor": INK,
        "text.color": INK,
        "xtick.color": INK,
        "ytick.color": INK,
        "xtick.major.width": 0.6,
        "ytick.major.width": 0.6,
        "xtick.major.size": 2.2,
        "ytick.major.size": 2.2,
        "lines.linewidth": 1.1,
        "legend.frameon": False,
        "figure.dpi": DPI,
        "savefig.dpi": DPI,
        "pdf.fonttype": 42,   # embed TrueType, not Type 3: editable + searchable
        "ps.fonttype": 42,
        "savefig.bbox": None,  # never crop: cropped output breaks the width spec
        "savefig.pad_inches": 0,
        "figure.facecolor": "white",
        "savefig.facecolor": "white",
        # Mathtext would embed a second family and render super/subscripts at
        # 0.7x. It is not used anywhere; these entries only ensure that if one
        # ever slipped in, it would not silently import DejaVu.
        "mathtext.fontset": "custom",
        "mathtext.rm": FAMILY,
        "mathtext.it": FAMILY + ":italic",
        "mathtext.bf": FAMILY + ":bold",
        "mathtext.default": "regular",
    })


def figure(width_cm, height_cm):
    """Create a figure whose PNG/PDF page is exactly width_cm x height_cm.
    Returns (fig, ax_or_None) for a single full-bleed axes."""
    return plt.figure(figsize=(width_cm * CM, height_cm * CM))


def save(fig, stem, width_cm, height_cm):
    """Write <stem>.pdf and <stem>.png at the exact requested size.

    The figure must already have been created at (width_cm, height_cm). We
    assert the resulting size rather than trusting the caller, because bbox
    cropping or a stray figsize would otherwise silently break the journal
    width requirement.
    """
    w_in, h_in = width_cm * CM, height_cm * CM
    fw, fh = fig.get_size_inches()
    if abs(fw - w_in) > 1e-6 or abs(fh - h_in) > 1e-6:
        raise RuntimeError(
            "figure is {:.3f}x{:.3f} in but {:.1f}x{:.1f} cm was requested "
            "({:.3f}x{:.3f} in)".format(fw, fh, width_cm, height_cm, w_in, h_in)
        )
    pdf = os.path.join(HERE, stem + ".pdf")
    png = os.path.join(HERE, stem + ".png")
    fig.savefig(pdf, format="pdf")
    fig.savefig(png, format="png", dpi=DPI)
    plt.close(fig)
    print("wrote {}  ({:.1f} x {:.1f} cm, {} dpi)".format(png, width_cm, height_cm, DPI))
    print("wrote {}  (vector)".format(pdf))
    return pdf, png
