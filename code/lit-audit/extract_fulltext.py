"""Extract the specific quantities we need from the full texts we CAN read.

Three sources are genuinely retrievable in this environment:
  - Fang et al. 2019, Nature (arXiv preprint PDF)  -> inactive-Li partition
  - Wang et al. 2026, Nat. Energy (Europe PMC XML)  -> stack-pressure / knee
  - Pang et al. 2025, Chem. Sci. (Europe PMC XML)   -> voltage fade decoupling
Everything else is behind Cloudflare and must be requested from the user.
"""
import io, os, re, sys, urllib.request, zlib

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fulltext-extracts.md")
HDR = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36"}


def get(url, timeout=60):
    return urllib.request.urlopen(urllib.request.Request(url, headers=HDR), timeout=timeout).read()


def pdf_text(data):
    chunks = []
    for m in re.finditer(rb"stream\r?\n(.*?)endstream", data, re.S):
        try:
            chunks.append(zlib.decompress(m.group(1)).decode("latin-1", "replace"))
        except Exception:
            pass
    raw = " ".join(chunks)
    strings = re.findall(r"\(((?:[^()\\]|\\.)*)\)", raw)
    txt = " ".join(strings)
    txt = txt.replace("\\(", "(").replace("\\)", ")")
    return " ".join(txt.split())


def xml_text(data):
    x = data.decode("utf-8", "replace")
    x = re.sub(r"<[^>]+>", " ", x)
    return " ".join(x.split())


def find(body, probes, window=320, maxhits=3):
    hits = []
    low = body.lower()
    for p in probes:
        start = 0
        while len(hits) < maxhits:
            i = low.find(p.lower(), start)
            if i < 0:
                break
            hits.append((p, body[max(0, i - window // 2): i + window]))
            start = i + 1
    return hits


out = ["# Full-text extracts — what the three readable papers actually say", ""]
out.append("Generated by `04-literature/_audit/extract_fulltext.py`. "
           "Only three of the cited works are retrievable from this environment; "
           "everything else is behind Cloudflare and is listed for the user to supply.")
out.append("")
note = []

# ---------- 1. Fang 2019 (arXiv preprint of the Nature paper) ----------
print("1. Fang 2019 (arXiv 1811.01029)")
try:
    body = pdf_text(get("https://arxiv.org/pdf/1811.01029"))
    out += ["## [8] Fang et al., *Nature* 2019 — quantifying inactive lithium", "",
            f"Source: arXiv preprint PDF, {len(body):,} characters extracted.", ""]
    for probe in ["inactive", "unreacted", "dead", "%"]:
        for p, ctx in find(body, [probe], maxhits=2):
            out.append(f"- **{p!r}** … {ctx} …")
            out.append("")
    out.append("")
    print(f"   extracted {len(body):,} chars")
except Exception as e:
    note.append(f"Fang extraction failed: {e}")
    print("   FAILED", e)

# ---------- 2 & 3. Europe PMC XML ----------
for label, pmcid, ref, title, probes in [
    ("Wang 2026", "PMC13391380", "[35]", "Wang et al., *Nat. Energy* 2026 — stack pressure",
     ["knee", "stack pressure", "pressure"]),
    ("Pang 2025", "PMC11792628", "[13]", "Pang et al., *Chem. Sci.* 2025 — voltage fade",
     ["voltage fade", "decoupl", "capacity fade"]),
]:
    print(f"{label} (Europe PMC {pmcid})")
    try:
        body = xml_text(get(f"https://www.ebi.ac.uk/europepmc/webservices/rest/{pmcid}/fullTextXML"))
        out += [f"## {ref} {title}", "",
                f"Source: Europe PMC full-text XML, {len(body):,} characters extracted.", ""]
        for probe in probes:
            for p, ctx in find(body, [probe], maxhits=2):
                out.append(f"- **{p!r}** … {ctx} …")
                out.append("")
        out.append("")
        print(f"   extracted {len(body):,} chars")
    except Exception as e:
        note.append(f"{label} extraction failed: {e}")
        print("   FAILED", e)

if note:
    out += ["## Extraction problems", ""] + [f"- {n}" for n in note]

io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"\nwrote {OUT}")
